"""Generate the small, independent 16x16 Chinese settings font from local UI font."""
from pathlib import Path
import json
from PIL import Image,ImageDraw,ImageFont
ROOT=Path(__file__).resolve().parents[1]
HDL=ROOT/'proj/src/user_source/hdl_source'
OUT=ROOT/'material/picture_settings_20261022'
CHARS=' 0123456789+-%>KEY画面调节亮度对比长按退出复原'

def main():
    assert len(set(CHARS))==len(CHARS) and len(CHARS)<=32
    OUT.mkdir(parents=True,exist_ok=True)
    font=ImageFont.truetype('C:/Windows/Fonts/msyhbd.ttc',16)
    words=[]
    atlas=Image.new('RGB',(len(CHARS)*16,16),'black')
    for glyph,ch in enumerate(CHARS):
        im=Image.new('L',(16,16),0);draw=ImageDraw.Draw(im)
        left,top,right,bottom=font.getbbox(ch)
        draw.text(((16-(right-left))//2-left,(16-(bottom-top))//2-top),ch,font=font,fill=255)
        rows=[]
        for y in range(16):
            value=sum((1<<(15-x)) for x in range(16) if im.getpixel((x,y))>=100)
            rows.append(value)
        if ch!=' ':assert any(rows),ch
        words.extend(rows);atlas.paste(im.convert('RGB'),(glyph*16,0))
    words.extend([0]*(512-len(words)))
    (OUT/'font.hex').write_text(''.join(f'{v:04x}\n' for v in words),encoding='ascii')
    text='// Generated by tools/build_picture_settings_font.py; separate from lyric fonts.\n'
    text+='function[15:0] ui_font_row;input[8:0] address;begin\n case(address)\n'
    text+=''.join(f" 9'd{i}:ui_font_row=16'h{v:04x};\n" for i,v in enumerate(words) if v)
    text+=" default:ui_font_row=16'd0;\n endcase\nend endfunction\n"
    (HDL/'picture_settings_font.vh').write_text(text,encoding='utf-8')
    osd=HDL/'picture_settings_osd.v'
    if osd.exists():
        source=osd.read_text(encoding='utf-8')
        start='// BEGIN GENERATED settings_font';stop='// END GENERATED settings_font'
        if start in source and stop in source:
            before=source.split(start,1)[0];after=source.split(stop,1)[1]
            osd.write_text(before+start+'\n'+text+stop+after,encoding='utf-8')
    (OUT/'font_manifest.json').write_text(json.dumps(dict(chars=CHARS,glyphs={c:i for i,c in enumerate(CHARS)},size=[16,16],source='C:/Windows/Fonts/msyhbd.ttc',rows=512),ensure_ascii=False,indent=2),encoding='utf-8')
    atlas.resize((len(CHARS)*32,32),Image.Resampling.NEAREST).save(OUT/'font_atlas.png')
    print('PASS',len(CHARS),'settings glyphs, 512 initialized rows; independent of lyric ROMs')

if __name__=='__main__':main()
